# -*- coding: utf-8 -*-
"""
মুদ্রা ফিক্স (ধাপ-৩)।

নীতি (bn উইকি রীতি অনুযায়ী):
- চিহ্ন (`R$`, `US$`, `$`, `€`, `£`, `₹`) রাখা হয় — ইনফোবক্সে এটাই প্রচলিত।
  শুধু পাশের সংখ্যা বাংলায় হয় (সেটা bn_digits_safe করে)।
- পূর্ণ নাম (`dollar`, `real`, `euro` …) বাংলায় হয়।
- কোড (`USD`, `BRL`, `EUR` …) দৃশ্যমান লেখায় থাকলে বাংলা নামে বদলায়,
  কিন্তু URL/ট্যাগের ভেতরে হাত দেয় না (bn_digits_safe-এর সুরক্ষা ব্যবহারের
  জন্য এই মডিউল টেক্সট-নোডে চালানোর নিয়ম পাইপলাইনে আছে)।

স্ক্রিনশট কেস:
  `R$ 932.166 billion` → `R$ ৯৩২.১৬৬ বিলিয়ন`
  `(US$ 172.917 billion)` → `(US$ ১৭২.৯১৭ বিলিয়ন)`
"""
import re

# ISO কোড → বাংলা নাম (দৃশ্যমান লেখায়)
CURRENCY_CODES = {
    "USD": "মার্কিন ডলার",
    "BRL": "ব্রাজিলীয় রিয়াল",
    "EUR": "ইউরো",
    "GBP": "পাউন্ড স্টার্লিং",
    "INR": "ভারতীয় রুপি",
    "BDT": "টাকা",
    "JPY": "জাপানি ইয়েন",
    "CNY": "চীনা ইউয়ান",
}

# পূর্ণ নাম → বাংলা (একবচন/বহুবচন)
CURRENCY_NAMES = {
    "dollar": "ডলার",
    "real": "রিয়াল",
    "euro": "ইউরো",
    "pound": "পাউন্ড",
    "rupee": "রুপি",
    "yen": "ইয়েন",
    "yuan": "ইউয়ান",
    "taka": "টাকা",
}


def fix_currency(text: str) -> str:
    s = text
    # 1. কোড: `USD 100` / `100 USD` → বাংলা নাম (সংখ্যা পরে বাংলায় হবে)
    for code, bn in CURRENCY_CODES.items():
        s = re.sub(rf"\b{code}\b", bn, s)
    # 2. নাম: dollars → ডলার
    for en, bn in CURRENCY_NAMES.items():
        s = re.sub(rf"\b{en}s?\b", bn, s, flags=re.IGNORECASE)
    return s
